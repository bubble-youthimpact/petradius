/* PetRadius — single pet profile page: pets/pet/?id=<slug>
   Pet details come from pet-data.js (generated by scripts/build.py). */
(function () {
  var root = document.getElementById('pet-root');
  if (!root) return;
  var id = new URLSearchParams(location.search).get('id') || '';
  var pages = window.PET_PAGES || {};
  var pet = Object.prototype.hasOwnProperty.call(pages, id) ? pages[id] : null;

  function setMeta(sel, attr, val) {
    var el = document.querySelector(sel);
    if (el) el.setAttribute(attr, val);
  }

  if (!pet) {
    document.title = 'Pet not found | PetRadius';
    root.innerHTML =
      '<div class="container"><div class="empty" style="text-align:center;padding:48px 0">' +
      '<h1>Pet not found</h1><p>This pet may have found a home, or the link is incorrect.</p>' +
      '<p><a class="btn btn-primary" href="../">See all pets</a></p></div></div>';
    return;
  }

  root.innerHTML = pet.html;
  var title = pet.name + ' | PetRadius';
  document.title = title;
  setMeta('meta[name="description"]', 'content', pet.desc);
  setMeta('meta[property="og:title"]', 'content', title);
  setMeta('meta[property="og:description"]', 'content', pet.desc);
  var canon = document.querySelector('link[rel="canonical"]');
  if (canon) {
    var url = canon.getAttribute('href').split('?')[0] + '?id=' + encodeURIComponent(id);
    canon.setAttribute('href', url);
    setMeta('meta[property="og:url"]', 'content', url);
  }
})();
